"""
Estimate a spec with Biogeme (``pip install dcmbench[biogeme]``, Biogeme ≥ 3.3).

Biogeme only estimates. The result is a ``SpecModel``, whose predictions come
from DCMBench's own evaluation of the spec. As a guard against compilation
mismatches, the log-likelihood DCMBench computes at Biogeme's estimates must
equal the one Biogeme reports. Draws for mixed logit are generated by
DCMBench and passed to Biogeme, so both see identical draws.
"""

from __future__ import annotations

import logging
from importlib import metadata

import numpy as np
import pandas as pd

from dcmbench.problem import ChoiceProblem
from dcmbench.specs import compute
from dcmbench.specs.draws import coefficient, variates
from dcmbench.specs.expression import evaluate
from dcmbench.specs.model import SpecModel
from dcmbench.specs.spec import Draws, Spec

CHOICE = "_DCMBENCH_CHOICE"


class EngineMismatchError(RuntimeError):
    """An engine's reported log-likelihood disagrees with DCMBench's evaluation of the spec."""


class _BiogemeExpressions:
    """Backend that builds Biogeme expressions instead of computing numbers."""

    name = "biogeme"

    def __init__(self):
        from biogeme.expressions import exp, log

        self.exp, self.log = exp, log

    @staticmethod
    def indicator(condition):
        return float(condition) if isinstance(condition, bool) else condition


def _sorted_for_panel(spec: Spec, problem: ChoiceProblem, data: pd.DataFrame) -> pd.DataFrame:
    if spec.draws is not None and spec.draws.panel:
        return data.sort_values(problem.group_column, kind="mergesort")
    return data


class BiogemeEstimator:
    """
    Fitter: ``BiogemeEstimator(spec, problem)(train) -> SpecModel``.

    ``check_tolerance`` bounds |LL_Biogeme − LL_DCMBench| relative to |LL|.
    """

    def __init__(self, spec: Spec, problem: ChoiceProblem, check_tolerance: float = 1e-6):
        compute.check_compatible(spec, problem)
        self.spec, self.problem, self.check_tolerance = spec, problem, check_tolerance

    def __call__(self, train: pd.DataFrame) -> SpecModel:
        import biogeme.biogeme as bio
        import biogeme.database as db
        from biogeme import models
        from biogeme.draws import RandomNumberGeneratorTuple
        from biogeme.expressions import Beta, Draws as BioDraws, MonteCarlo, PanelLikelihoodTrajectory, Variable, log
        from biogeme.nests import NestsForNestedLogit, OneNestForNestedLogit
        from biogeme.parameters import Parameters
        from biogeme.results_processing import EstimateVarianceCovariance

        spec, problem = self.spec, self.problem
        train = _sorted_for_panel(spec, problem, train)
        ids = {alt: i + 1 for i, alt in enumerate(problem.alternatives)}

        columns = set(spec.data_columns())
        columns |= {c for c in problem.availability.values() if c is not None}
        if spec.draws is not None and spec.draws.panel:
            columns.add(problem.group_column)
        frame = train[sorted(columns)].astype(float).reset_index(drop=True)
        frame[CHOICE] = problem.choices(train).map(ids).to_numpy()
        database = db.Database(spec.name, frame)

        backend = _BiogemeExpressions()
        env = {c: Variable(c) for c in spec.data_columns()}
        betas = {n: Beta(n, p.start, p.lower, p.upper, 1 if p.fixed else 0) for n, p in spec.parameters.items()}
        env.update(betas)
        generators = {}
        for index, (name, rp) in enumerate(spec.random_parameters.items()):
            generator_name = f"DCMBENCH_{index}"

            def generate(sample_size, number_of_draws, rp=rp, index=index):
                settings = Draws(number_of_draws, spec.draws.seed, spec.draws.type, spec.draws.panel)
                return variates(rp, sample_size, settings, index)

            generators[generator_name] = RandomNumberGeneratorTuple(generate, f"DCMBench draws for {name}")
            draw = BioDraws(f"{name}_DRAW", generator_name)
            env[name] = coefficient(rp, betas[rp.mean], betas[rp.spread], draw, backend)

        V = {ids[alt]: evaluate(spec.parsed[alt], env, backend) for alt in problem.alternatives}
        av = {ids[alt]: (1 if problem.availability_column(alt) is None else Variable(problem.availability_column(alt)))
              for alt in problem.alternatives}
        choice = Variable(CHOICE)

        if spec.model == "NL":
            nests = NestsForNestedLogit(
                choice_set=list(ids.values()),
                tuple_of_nests=tuple(
                    OneNestForNestedLogit(nest_param=betas[n.parameter], list_of_alternatives=[ids[a] for a in n.alternatives],
                                          name=n.name)
                    for n in spec.nests
                ),
            )
            logprob = models.lognested(V, av, nests, choice)
        elif spec.model == "MXL":
            probability = models.logit(V, av, choice)
            if spec.draws.panel:
                database.panel(problem.group_column)
                probability = PanelLikelihoodTrajectory(probability)
            logprob = log(MonteCarlo(probability))
        else:
            logprob = models.loglogit(V, av, choice)

        kwargs = dict(parameters=Parameters(), generate_html=False, generate_yaml=False, save_iterations=False)
        if generators:
            kwargs.update(random_number_generators=generators, number_of_draws=spec.draws.number)
        model = bio.BIOGEME(database, logprob, **kwargs)
        model.model_name = spec.name
        biogeme_logger = logging.getLogger("biogeme")
        level = biogeme_logger.level
        biogeme_logger.setLevel(logging.ERROR)
        try:
            results = model.estimate()
        finally:
            biogeme_logger.setLevel(level)

        estimated = results.get_beta_values()
        values = {n: (p.start if p.fixed else estimated[n]) for n, p in spec.parameters.items()}
        std_errors = {n: results.get_parameter_std_err(n, EstimateVarianceCovariance.ROBUST)
                      for n in spec.free_parameters()}
        fitted = SpecModel(
            spec, problem, values, std_errors,
            converged=bool(results.algorithm_has_converged),
            engine="biogeme",
            engine_details={"biogeme": metadata.version("biogeme"), "engine_loglikelihood": float(results.final_loglikelihood)},
        )
        ours, theirs = fitted.loglikelihood(train), float(results.final_loglikelihood)
        if abs(ours - theirs) > self.check_tolerance * max(1.0, abs(theirs)):
            raise EngineMismatchError(
                f"Biogeme reports LL {theirs:.6f} but DCMBench evaluates the spec at {ours:.6f}; "
                "the spec was compiled inconsistently"
            )
        return fitted
