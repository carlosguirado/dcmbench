"""
Simulation draws, generated by DCMBench and shared with every engine.

The same function supplies draws to Biogeme (as a user-defined random number
generator) and to DCMBench's own probability code, so a mixed logit is
estimated and evaluated on identical draws, and predictions are
deterministic (common random numbers across perturbations).
"""

from __future__ import annotations

import numpy as np
from scipy.stats import norm, qmc

from dcmbench.specs.spec import Draws, RandomParameter


def standard_draws(base: str, n_units: int, settings: Draws, index: int) -> np.ndarray:
    """
    ``(n_units, settings.number)`` standard draws (``"normal"`` or ``"uniform"``)
    for the ``index``-th random parameter. Depends only on these arguments.
    """
    seed = settings.seed + 1000 * index
    if settings.type == "pseudo":
        rng = np.random.default_rng(seed)
        values = rng.standard_normal((n_units, settings.number)) if base == "normal" \
            else rng.random((n_units, settings.number))
        return values
    # Scrambled Halton, one dimension per random parameter, n_units × number points.
    sampler = qmc.Halton(d=1, scramble=True, seed=seed)
    uniform = sampler.random(n_units * settings.number).reshape(n_units, settings.number)
    uniform = np.clip(uniform, 1e-12, 1 - 1e-12)
    return norm.ppf(uniform) if base == "normal" else uniform


def triangular_from_uniform(u):
    """Symmetric triangular on [−1, 1] by inverse CDF; works on numpy arrays."""
    return np.where(u < 0.5, np.sqrt(2 * u) - 1, 1 - np.sqrt(2 * (1 - u)))


def variates(rp: RandomParameter, n_units: int, settings: Draws, index: int) -> np.ndarray:
    """The draw each coefficient formula expects: ξ (normal), u (uniform) or t (triangular)."""
    values = standard_draws(rp.base, n_units, settings, index)
    return triangular_from_uniform(values) if rp.distribution == "triangular" else values


def coefficient(rp: RandomParameter, mean, spread, draw, backend):
    """The random coefficient's value given its mean/spread values and standard draws."""
    if rp.distribution == "normal":
        return mean + spread * draw
    if rp.distribution == "lognormal":
        return rp.sign * backend.exp(mean + spread * draw)
    if rp.distribution == "uniform":
        return mean + spread * (2 * draw - 1)
    return mean + spread * draw  # triangular: draw is already the triangular variate
